import { defineConfig } from 'vitest/config'

export default defineConfig({
  test: {
    include: ['packages/*/test/**/*.test.ts'],
    benchmark: { include: ['packages/*/bench/**/*.bench.ts'] },

    /*
     * 30 секунд вместо дефолтных 5.
     *
     * Почти каждый тест здесь — это десятки полных боёв, а не проверка одной
     * функции: иначе балансное утверждение не проверишь, один бой ничего не
     * доказывает. После ADR-009 бой длится втрое дольше (9.5 → 30 с игрового
     * времени), и тесты, укладывавшиеся в 5 секунд на локальной машине, стали
     * выпадать за них на раннере CI — который заметно медленнее.
     *
     * Проставлять timeout на каждый it() по мере того, как он начнёт падать, —
     * это чинить симптом по одному и держать CI красным между правками.
     * Глобальное значение честнее: оно отражает реальную природу этого набора
     * тестов. Отдельные timeout остаются там, где тест заведомо длинный
     * (1000 прогонов детерминизма, fuzz на 200 боёв) — как документация к
     * стоимости, а не как заплатка.
     */
    testTimeout: 30_000,
  },
})
