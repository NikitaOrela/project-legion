/**
 * Hold Ground — механика павизы из первоисточника (Elite Shield Guard).
 *
 * Пока павиза держит контакт, её защита растёт на HOLD_DEF_STEP_PCT каждые
 * HOLD_PERIOD тиков, до HOLD_MAX_STACKS ступеней. Контакт разорван — стаки
 * обнуляются.
 *
 * ЗАЧЕМ ЭТО НУЖНО НАМ. Без кита павиза оказалась худшим классом (9% среднего
 * винрейта), и связка «стена + стрелки» проигрывала простому «пехота +
 * стрелки»: пехота во фронте даёт втрое больше урона, а живёт лишь на 73%
 * меньше. То есть держать было невыгоднее, чем бить, — и весь смысл класса
 * пропадал.
 *
 * Hold Ground это чинит правильным образом: он награждает именно за то, ради
 * чего класс существует. Чем дольше стена стоит, тем труднее её проломить, а
 * значит тем больше успевают отстрелять те, кто за ней. Синергия появляется
 * из механики, а не из подкрученного числа.
 *
 * ОТЛИЧИЕ ОТ ОРИГИНАЛА: там стаки сбрасываются при СМЕНЕ цели, у нас — при
 * разрыве контакта. Разница в том, что наша павиза сохраняет стаки, когда
 * враг перед ней умер и его сменил следующий из очереди. Осознанное
 * упрощение: хранить прежнюю цель — это ещё один массив на 840 юнитов ради
 * поведения, которое игрок на поле не различит.
 */
export const HOLD_PERIOD = 1 * TICK_HZ
export const HOLD_DEF_STEP_PCT = 10
export const HOLD_MAX_STACKS = 5

/**
 * Сколько юнитов одновременно могут держать одну цель. ГЛАВНЫЙ РЫЧАГ ADR-009.
 *
 * ЗАЧЕМ. Диагноз BALANCE_01: 156 пар архетипов из 156 вне коридора 40–60%,
 * матрица состоит из нулей и сотен. Причина — квадратичный закон Ланчестера.
 * Он возникает ровно из одного допущения: урон стороны пропорционален числу её
 * живых юнитов, и каждый из них может бить кого угодно. Отсюда петля: у кого
 * больше живых — тот быстрее убивает — тем больше у него остаётся живых.
 * Преимущество в 15% на старте даёт 100% побед.
 *
 * Но у Ланчестера есть и ВТОРОЙ закон — линейный. Он описывает бой, где
 * ширина соприкосновения ограничена и схватка распадается на поединки. Там
 * преимущество даёт пропорциональный, а не тотальный результат — то есть ровно
 * то распределение исходов, которое нам нужно.
 *
 * Переход от квадратичного закона к линейному — это и есть ограничение
 * фронта. Физически оно очевидно: вокруг одного бойца физически не помещается
 * двадцать. Мы это просто не моделировали, и вся математика боя жила в
 * квадратичном режиме.
 *
 * Лишние атакующие не исчезают: они не получают цели, продолжают идти вперёд
 * и подхватывают цель, как только та освобождается. Резерв, а не простой.
 *
 * Дальний бой окружает свободнее ближнего — отсюда разные значения.
 */
export const MAX_ATTACKERS_MELEE = 3
export const MAX_ATTACKERS_RANGED = 6

