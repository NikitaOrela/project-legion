/**
 * Кого класс ИЩЕТ на поле — приоритет цели, а не множитель урона.
 *
 * Это главная находка ресерча и, вероятно, настоящий ответ на Ланчестера.
 *
 * Множитель без приоритета — лотерея: контр срабатывает, только если юниты
 * случайно встретились. Копейщик, который не ищет кавалерию, бьёт того, кто
 * ближе, и его +120% не срабатывает никогда. С приоритетом контр становится
 * обещанием, которое игрок закладывает в расстановку.
 *
 * И отдельно — против петли Ланчестера: приоритеты РАСПЫЛЯЮТ урон. Без них
 * вся армия фокусируется на ближайшем юните и снимает цели одну за одной,
 * ускоряя обратную связь. С ними каждый класс уходит к своей добыче, и
 * концентрация огня падает сама собой.
 *
 * NO_TARGET (-1) = у класса нет предпочтений, бьёт ближайшего.
 * Значения — из `/en/soldiers` ремейка, адаптированы под наш ростер.
 */
